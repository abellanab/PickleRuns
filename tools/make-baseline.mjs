// @ts-check
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import postgres from 'postgres';

const __dir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dir, '..');

const envVars = Object.fromEntries(
  readFileSync(resolve(repoRoot, '.env'), 'utf8')
    .split('\n')
    .filter((line) => line.trim() && !line.startsWith('#'))
    .map((line) => {
      const [key, ...rest] = line.split('=');
      return [key.trim(), rest.join('=').trim()];
    })
);

const url = envVars.DIRECT_URL;
if (!url) {
  console.error('DIRECT_URL not found in .env');
  process.exit(1);
}

/** @param {string} name */
const ident = (name) => (/^[a-z_][a-z0-9_]*$/.test(name) ? name : `"${name.replace(/"/g, '""')}"`);
/** @param {string} value */
const literal = (value) => `'${value.replace(/'/g, "''")}'`;

const sql = postgres(url, { prepare: false, max: 1 });

/** @type {string[]} */
const out = [];
/** @param {string} title */
const section = (title) => out.push('', `-- ==== section: ${title} ====`);

const counts = { enums: 0, tables: 0, functions: 0, policies: 0, triggers: 0, indexes: 0, constraints: 0 };

try {
  // Fully qualified output (public.x) keeps the file independent of search_path.
  await sql.unsafe('SET search_path = pg_catalog');

  const tables = await sql.unsafe(`
    SELECT c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relreplident
    FROM pg_class c
    WHERE c.relnamespace = 'public'::regnamespace
      AND c.relkind = 'r'
      AND c.relname <> 'pgmigrations'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.classid = 'pg_class'::regclass AND d.deptype = 'e')
    ORDER BY c.relname`);

  const sequences = await sql.unsafe(`
    SELECT c.relname FROM pg_class c
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'S' AND c.relname <> 'pgmigrations_id_seq'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i')`);
  if (sequences.length > 0) {
    throw new Error(`Standalone sequences are not supported by the baseline generator: ${sequences.map((s) => s.relname).join(', ')}`);
  }

  const enums = await sql.unsafe(`
    SELECT t.typname, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS labels
    FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
    WHERE t.typnamespace = 'public'::regnamespace
    GROUP BY t.typname ORDER BY t.typname`);

  const today = new Date().toISOString().slice(0, 10);
  out.push(
    '-- GENERATED FILE - DO NOT EDIT.',
    '-- Generated by tools/make-baseline.mjs from the live database public schema.',
    `-- Generated on: ${today}`,
    '-- Regenerate with: npm run db:baseline:generate',
    '',
    'SET check_function_bodies = off;',
    'SET search_path = public;'
  );

  section('enums');
  for (const e of enums) {
    out.push(`CREATE TYPE public.${ident(e.typname)} AS ENUM (${e.labels.map(literal).join(', ')});`);
    counts.enums++;
  }

  section('tables');
  for (const t of tables) {
    const cols = await sql.unsafe(
      `
      SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
             a.attgenerated, a.attidentity, pg_get_expr(d.adbin, d.adrelid) AS def
      FROM pg_attribute a
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum`,
      [t.oid]
    );
    const lines = cols.map((c) => {
      let line = `  ${ident(c.attname)} ${c.type}`;
      if (c.attidentity === 'a') line += ' GENERATED ALWAYS AS IDENTITY';
      else if (c.attidentity === 'd') line += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (c.attgenerated === 's') line += ` GENERATED ALWAYS AS (${c.def}) STORED`;
      else if (c.def !== null) line += ` DEFAULT ${c.def}`;
      if (c.attnotnull) line += ' NOT NULL';
      return line;
    });
    out.push(`CREATE TABLE public.${ident(t.relname)} (`, lines.join(',\n'), ');');
    counts.tables++;
  }

  section('functions');
  const functions = await sql.unsafe(`
    SELECT p.oid, pg_get_functiondef(p.oid) AS def
    FROM pg_proc p
    WHERE p.pronamespace = 'public'::regnamespace
      AND p.prokind IN ('f', 'p')
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.classid = 'pg_proc'::regclass AND d.deptype = 'e')
    ORDER BY p.proname, p.oid::regprocedure::text`);
  for (const f of functions) {
    out.push(`${f.def.trimEnd()};`, '');
    counts.functions++;
  }

  const constraints = await sql.unsafe(`
    SELECT c.conrelid::regclass::text AS tbl, c.conname, c.contype, pg_get_constraintdef(c.oid) AS def
    FROM pg_constraint c
    JOIN pg_class r ON r.oid = c.conrelid
    WHERE r.relnamespace = 'public'::regnamespace AND r.relkind = 'r' AND r.relname <> 'pgmigrations'
      AND c.contype IN ('p', 'u', 'c', 'x', 'f')
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = r.oid AND d.classid = 'pg_class'::regclass AND d.deptype = 'e')
    ORDER BY CASE c.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'x' THEN 1 WHEN 'c' THEN 2 ELSE 3 END, r.relname, c.conname`);
  const addConstraint = (/** @type {{tbl: string, conname: string, def: string}} */ c) =>
    `ALTER TABLE ${c.tbl} ADD CONSTRAINT ${ident(c.conname)} ${c.def};`;

  section('constraints');
  for (const c of constraints.filter((c) => c.contype !== 'f')) {
    out.push(addConstraint(c));
    counts.constraints++;
  }

  section('foreign-keys');
  for (const c of constraints.filter((c) => c.contype === 'f')) {
    out.push(addConstraint(c));
    counts.constraints++;
  }

  section('indexes');
  const indexes = await sql.unsafe(`
    SELECT pg_get_indexdef(i.indexrelid) AS def
    FROM pg_index i
    JOIN pg_class ic ON ic.oid = i.indexrelid
    JOIN pg_class tc ON tc.oid = i.indrelid
    WHERE tc.relnamespace = 'public'::regnamespace AND tc.relkind = 'r' AND tc.relname <> 'pgmigrations'
      AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = tc.oid AND d.classid = 'pg_class'::regclass AND d.deptype = 'e')
    ORDER BY tc.relname, ic.relname`);
  for (const i of indexes) {
    out.push(`${i.def};`);
    counts.indexes++;
  }

  section('row-level-security');
  for (const t of tables.filter((t) => t.relrowsecurity)) {
    out.push(`ALTER TABLE public.${ident(t.relname)} ENABLE ROW LEVEL SECURITY;`);
    if (t.relforcerowsecurity) out.push(`ALTER TABLE public.${ident(t.relname)} FORCE ROW LEVEL SECURITY;`);
  }

  section('policies');
  const policies = await sql.unsafe(`
    SELECT tablename, policyname, permissive, roles, cmd, qual, with_check
    FROM pg_policies
    WHERE schemaname = 'public' AND tablename <> 'pgmigrations'
    ORDER BY tablename, policyname`);
  for (const p of policies) {
    const roles = /** @type {string[]} */ (Array.isArray(p.roles) ? p.roles : String(p.roles).replace(/[{}]/g, '').split(','))
      .map((r) => (r.toLowerCase() === 'public' ? 'PUBLIC' : ident(r)))
      .join(', ');
    let stmt = `CREATE POLICY ${ident(p.policyname)} ON public.${ident(p.tablename)} AS ${p.permissive} FOR ${p.cmd} TO ${roles}`;
    if (p.qual !== null) stmt += ` USING (${p.qual})`;
    if (p.with_check !== null) stmt += ` WITH CHECK (${p.with_check})`;
    out.push(`${stmt};`);
    counts.policies++;
  }

  section('triggers');
  const triggers = await sql.unsafe(`
    SELECT pg_get_triggerdef(g.oid) AS def
    FROM pg_trigger g
    JOIN pg_class c ON c.oid = g.tgrelid
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND c.relname <> 'pgmigrations'
      AND NOT g.tgisinternal
    ORDER BY c.relname, g.tgname`);
  for (const g of triggers) {
    out.push(`${g.def};`);
    counts.triggers++;
  }

  section('auth-triggers');
  const authTriggers = await sql.unsafe(`
    SELECT g.tgname, pg_get_triggerdef(g.oid) AS def
    FROM pg_trigger g
    JOIN pg_proc p ON p.oid = g.tgfoid
    WHERE g.tgrelid = 'auth.users'::regclass
      AND NOT g.tgisinternal
      AND p.pronamespace = 'public'::regnamespace
    ORDER BY g.tgname`);
  for (const g of authTriggers) {
    out.push(`DROP TRIGGER IF EXISTS ${ident(g.tgname)} ON auth.users;`, `${g.def};`);
    counts.triggers++;
  }

  section('replica-identity');
  for (const t of tables.filter((t) => t.relreplident === 'f')) {
    out.push(`ALTER TABLE public.${ident(t.relname)} REPLICA IDENTITY FULL;`);
  }

  section('realtime-publication');
  const published = await sql.unsafe(`
    SELECT tablename FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename <> 'pgmigrations'
    ORDER BY tablename`);
  for (const p of published) {
    out.push(
      'DO $baseline$',
      'BEGIN',
      "  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')",
      `    AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = ${literal(p.tablename)}) THEN`,
      `    ALTER PUBLICATION supabase_realtime ADD TABLE public.${ident(p.tablename)};`,
      '  END IF;',
      'END',
      '$baseline$;'
    );
  }

  const migrations = await sql.unsafe('SELECT name FROM public.pgmigrations ORDER BY id');

  const baselineDir = resolve(repoRoot, 'db', 'baseline');
  mkdirSync(baselineDir, { recursive: true });
  writeFileSync(resolve(baselineDir, 'schema.sql'), `${out.join('\n')}\n`);
  writeFileSync(
    resolve(baselineDir, 'applied-migrations.json'),
    `${JSON.stringify(migrations.map((m) => m.name), null, 2)}\n`
  );

  console.log(`Wrote db/baseline/schema.sql: ${JSON.stringify(counts)}`);
  console.log(`Wrote db/baseline/applied-migrations.json: ${migrations.length} migrations`);
} finally {
  await sql.end();
}
